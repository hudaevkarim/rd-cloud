-- Заявка на вход: одна строка на человека.
--
-- ─── Почему индекс меняется ───────────────────────────────────────────────────
--
-- Было `@@unique([roomId, userId, status])`. Индекс задумывался как «не больше
-- одной заявки, ожидающей ответа», но он запрещал больше одной строки на каждый
-- статус. Отсюда падение: человек вошёл, его исключили, он подал заявку снова,
-- и одобрение падало с 500 — новая строка со статусом `approved` сталкивалась
-- с прежней, уже одобренной.
--
-- Наблюдалось в живом браузере: `PrismaClientKnownRequestError`, P2002 на
-- `JoinRequest_roomId_userId_status_key` при `joinRequest.update()`.
--
-- ─── Почему «одна строка», а не частичный индекс ──────────────────────────────
--
-- Гипотетически можно было оставить историю и взять уникальный индекс
-- `(roomId, userId) WHERE status = 'pending'`. От такого индекса пришлось бы
-- отказаться: Prisma не умеет объявлять частичные индексы, и при следующем
-- `migrate dev` он увидел бы в базе лишний индекс и предложил его удалить —
-- то есть миграция тихо откатила бы сама себя.
--
-- Частичный индекс давал бы историю, которой никто не читает: список заявок
-- отдаёт только ожидающие (`status: 'pending'`), и ни один запрос не читает
-- одобренные и отклонённые. Поэтому строка — это текущее состояние, а не
-- запись в журнале.

-- Дубликаты, оставшиеся от прежнего индекса: по паре «комната + человек» их
-- могло быть до трёх (по одной на статус). Оставляем ту, что важнее для работы:
-- ожидающую, а если её нет — самую свежую.
DELETE FROM "JoinRequest" j
USING "JoinRequest" k
WHERE j."roomId" = k."roomId"
  AND j."userId" = k."userId"
  AND (
    -- k важнее: у неё статус `pending`, а у j нет,
    (k."status" = 'pending' AND j."status" <> 'pending')
    -- либо обе одного статуса и k свежее
    OR (k."status" = j."status" AND (k."createdAt", k."id") > (j."createdAt", j."id"))
  );

DROP INDEX "JoinRequest_roomId_userId_status_key";

CREATE UNIQUE INDEX "JoinRequest_roomId_userId_key" ON "JoinRequest"("roomId", "userId");