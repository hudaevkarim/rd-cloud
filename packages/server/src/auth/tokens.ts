import { createHash, randomBytes, timingSafeEqual } from 'node:crypto';

/**
 * Токены доступа.
 *
 * ─── Почему непрозрачный токен, а не JWT ─────────────────────────────────────
 *
 * Один процесс, двадцать пользователей, горизонтального масштабирования нет.
 * JWT в этом setup не даёт ничего, чего не даёт сравнение хеша, но добавляет
 * секрет, который надо хранить и красть, и черту срока действия, которую здесь
 * попросили не вводить. Поэтому сессия — это сам токен, а в базе лежит только
 * его sha256.
 *
 * ─── Почему sha256, а не bcrypt ──────────────────────────────────────────────
 *
 * Паролей здесь нет вообще, а токен содержит 256 бит энтропии. Bcrypt на
 * 256-битном секрете не даёт ничего: он защищает от подбора коротких
 * паролей, которых тут не существует, и стоил бы 100 мс задержки на каждый
 * вход. Для токена правильный выбор — быстрый хеш: угадать его перебором
 * невозможно, а украденный дамп базы бесполезен без исходного токена.
 *
 * ─── Чего тут нет ────────────────────────────────────────────────────────────
 *
 * Срока действия и возможности отозвать один токен, не удаляя пользователя.
 * Токен выдаётся админом вручную и живёт, пока не сменится. Это осознанно:
 * см. README, раздел «Аутентификация».
 */

/**
 * 32 случайных байта в base64url.
 *
 * base64url, а не обычный base64: в токене не должно быть `+`, `/` и `=`,
 * которые пришлось бы вырезать при копировании в буфер обмена или при вставке
 * в URL.
 */
export function generateToken(): string {
  return randomBytes(32).toString('base64url');
}

/** sha256 от токена, hex. Именно это значение лежит в колонке `tokenHash`. */
export function hashToken(token: string): string {
  return createHash('sha256').update(token, 'utf8').digest('hex');
}

/**
 * Сравнение токена с хешем за постоянное время.
 *
 * Утечка по времени здесь почти не читается: сравниваются хеши, а не токены, и
 * их нельзя перебирать по сети. Но наивное `===` выглядело бы неправильно, и
 * его написали бы один раз, а потом забыли бы, что здесь было неравенство.
 *
 * `timingSafeEqual` бросает исключение на разной длине, поэтому длины
 * сравниваются заранее — иначе проверка была бы не постоянного времени.
 */
export function verifyToken(token: string, expectedHash: string): boolean {
  const actual = Buffer.from(hashToken(token), 'hex');
  const expected = Buffer.from(expectedHash, 'hex');
  if (actual.length !== expected.length || actual.length === 0) return false;
  return timingSafeEqual(actual, expected);
}