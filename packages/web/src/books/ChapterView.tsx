import { useEffect, useRef } from 'react';
import { renderChapter } from '@rd/library/render';
import type { ChapterBlock, WireComment } from '../api/types.js';
import { applyCommentMarkers, clearCommentMarkers } from './comment-markers.js';

/**
 * Глава книги, построенная рендерером библиотеки.
 *
 * ─── Почему не React ─────────────────────────────────────────────────────────
 *
 * `@rd/library/render` намеренно строит DOM через `createElement` и
 * `textContent`. Это не недосмотр, а решение по безопасности: содержимое книги
 * недоверенное, и путь «взять строку и вставить через `innerHTML`» требует
 * санитайзера, у которого рано или поздно находится новый вектор. Здесь текст
 * попадает в `textContent`, где всегда остаётся текстом.
 *
 * Отсюда следствие, важное для интеграции: разметка главы не принадлежит
 * React. Поэтому она не отрисовывается JSX, а кладётся в контейнер, и React
 * управляет только самим контейнером.
 */
export function ChapterView({
  blocks,
  baseDir,
  comments,
  chapterIndex,
  onRendered,
}: {
  blocks: ChapterBlock[];
  /** Каталог главы внутри архива: нужен для разрешения относительных ссылок. */
  baseDir?: string;
  /**
   * Комментарии текущей главы — фильтрует страница.
   *
   * Фильтр не здесь намеренно: компонент не знает ни про номер главы в
   * книге, ни про то, откуда взялись комментарии, и знать ему не нужно.
   * Страница решает, что показать, компонент — как это показать.
   */
  comments?: WireComment[];
  /**
   * Номер главы, к которой относятся переданные комментарии.
   *
   * Нужен потому, что `data-block` — номер блока **внутри главы**: у каждой
   * главы блоки нумеруются с нуля. Без него комментарий из пятой главы с
   * `blockIndex: 0` подсветил бы первый блок текущей. Координаты при этом
   * сходятся — цитата находится, — и подсвечено оказывается место в другой
   * главе. Молча.
   */
  chapterIndex?: number;
  /**
   * Вызывается после того, как блоки появились в DOM. Первым аргументом идёт
   * сам контейнер.
   *
   * Нужен для восстановления позиции: прокручивать и мерить блок можно только
   * после того, как он существует.
   *
   * ─── Почему контейнер передаётся здесь, а не берётся страницей ────────────
   *
   * Глава может прийти в том же проходе рендера, в котором страница создаёт
   * прокручиваемый блок впервые. Ссылка на элемент в этот момент ещё пуста —
   * она заполнится во время фиксации, а эффекты главы выполняются сразу после
   * неё. Страница, взявшая элемент из своей ссылки, получила бы `null` и
   * решила бы, что восстанавливать некуда: книга открывалась бы с начала.
   *
   * Наблюдалось в живом браузере: позиция `scrollY: 8000` в хранилище, а глава
   * открывалась наверху.
   */
  onRendered?: (host: HTMLElement, blocks: ChapterBlock[]) => void;
}) {
  const ref = useRef<HTMLDivElement>(null);

  /*
    Обработчик лежит вне зависимостей намеренно: страница передаёт новую
    замыканию на каждом рендере, и с ней в зависимостях эффект перерисовывал бы
    главу бесконечно. Актуальная версия читается через ref.
  */
  const onRenderedRef = useRef(onRendered);
  onRenderedRef.current = onRendered;

  /*
    Эффекта два, а не один — и это не разделение ради порядка в файле.

    Сначала маркеры накладывались в том же проходе, что и рендер, и
    `comments` стояли в зависимостях этого эффекта. Живая проверка показала
    прыжок в начало главы: `onRendered` страницы прокручивает блок к
    сохранённому месту, и лишний рендер ставил `scrollTop = 0` поверх неё.

    Причина структурная: страница считает любой вызов `onRendered` сменой
    главы, потому что раньше она и была единственной причиной рендера. Лечить
    это на стороне страницы — то есть учитывать в ней, что глава могла не
    смениться, — значило бы усложнять её ради компонента, который в этом не
    виноват.

    Второй эффект решает задачу с другой стороны: он не трогает рендерер, не
    зовёт `onRendered` и не двигает прокрутку, а только ходит по уже готовому
    дереву. Эффекты одного компонента выполняются в порядке объявления, так
    что маркеры всегда видят результат рендера, в том числе на первом проходе.
  */

  useEffect(() => {
    const host = ref.current;
    if (host === null) return;

    /*
      Чистим контейнер сами: React не владеет его содержимым и не уберёт
      прошлую главу, а без очистки старая осталась бы под новой — и человек
      увидел бы две главы как одну.

      Зависимость — `blocks` по ссылке: блоки пересобираются на каждый ответ
      сервера, и так ловится и смена главы, и возврат в ту же главу с другой
      прокруткой. Сравнение по числу блоков второй случай бы пропустило.
    */
    host.replaceChildren();
    host.appendChild(renderChapter({ blocks }, baseDir === undefined ? {} : { baseDir }));

    onRenderedRef.current?.(host, blocks);
  }, [blocks, baseDir]);

  /*
    Маркеры — отдельным проходом по готовому дереву.

    Порядок обязателен: `applyCommentMarkers` ищет цитату по `data-block` в
    готовом DOM, поэтому до рендера искать нечего.

    Здесь `comments` в зависимостях, в отличие от `blocks`. Комментарии
    приходят отдельно от главы и меняются без её смены: из сокета в 7.4.2.4,
    из ответа списка. Смешивать их с рендером нельзя — это ровно тот прыжок в
    начало, о котором сказано выше.

    Старые маркеры снимаются явно, а не «сами собой» через `replaceChildren`:
    этот эффект перезапускается и без перерисовки главы, и без
    `clearCommentMarkers` два маркера на одном месте наложились бы друг на
    друга. Внутри `clear` стоит `normalize()`, поэтому после него блок снова
    состоит из исходных текстовых узлов и координаты следующих наложений
    считаются заново.

    `blocks` в зависимостях здесь нужен: смена главы обязана снять маркеры
    прошлой, даже если `comments` ссылкой не изменились — а они не изменятся,
    когда комментариев к книге не было вовсе.
  */
  useEffect(() => {
    const host = ref.current;
    if (host === null || chapterIndex === undefined) return;
    clearCommentMarkers(host);
    if (comments !== undefined && comments.length > 0) {
      applyCommentMarkers(host, comments, chapterIndex);
    }
  }, [blocks, comments, chapterIndex]);

  return <div className="chapter" ref={ref} />;
}