/**
 * Как прокручивать: плавно или сразу.
 *
 * ─── Зачем спрашивать, а не всегда просить плавно ─────────────────────────────
 *
 * Наблюдалось в браузере: `scrollIntoView({ behavior: 'smooth' })` на телефоне
 * и в режиме «меньше движения» не прокручивает страницу вообще — а прокрутка
 * молча не сработавшая хуже её отсутствия, потому что человек нажал на
 * комментарий и остался на месте, решив, что ссылка сломана.
 *
 * Проверка идёт через `matchMedia`, а не через галочку в настройках: движение,
 * которое человек просил не показывать, нельзя ему показывать и в прокрутке.
 * Правило то же, что у токена `--transition` в `tokens.css`.
 */
export function scrollBehavior(): ScrollBehavior {
  if (typeof window.matchMedia !== 'function') return 'auto';
  return window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth';
}