/**
 * Кружок с инициалами.
 *
 * ─── Почему инициалы, а не картинка ───────────────────────────────────────────
 *
 * Аватары в проекте не загружаются: их нет ни в одной таблице, только поле
 * `avatar`, которое всегда `null`. Строить вокруг пустого поля — значит
 * показать серый кружок с буквой-заглушкой, что читается как «сломанное
 * изображение».
 *
 * Инициалы из имени — единственное, что есть всегда. И привычны: так
 * показывают себя все, кроме тех, у кого аватар загружен.
 *
 * ─── Почему тут скругление ──────────────────────────────────────────────────
 *
 * Круг — единственное место, где `--radius` не ноль: круг и есть исключение из
 * правила «никаких скруглений». Плоский квадрат на месте кружка читался бы как
 * квадрат, а не как обозначение человека.
 */
export function Avatar({
  name,
  size = 26,
  online = false,
}: {
  name: string;
  size?: number;
  /** Точка присутствия. Рисуется как маркер, а не как отдельный элемент. */
  online?: boolean;
}) {
  return (
    <span
      className="avatar"
      style={{ width: size, height: size }}
      title={name}
      // Инициалы объявляются скринридеру как текст: иначе круг был бы безымянным
      // элементом, и список участников читался бы как «, , ,».
      aria-label={name}
      role="img"
    >
      {initialsOf(name)}
      {online === true && <span className="avatar__dot" aria-label="сейчас читает" />}
    </span>
  );
}

/**
 * Инициалы из отображаемого имени.
 *
 * Берутся первая буква первого и последнего слова: `Анна Каренина` → «АК», а не
 * «АК» из первых букв всех слов — иначе длинное имя давало бы четыре буквы и
 * кружок переставал читаться.
 *
 * Имя без пробелов (`admin`) даёт одну букву: вторую брать неоткуда.
 */
export function initialsOf(name: string): string {
  const parts = name.trim().split(/\s+/).filter((p) => p !== '');
  if (parts.length === 0) return '?';

  // Распад по точкам, а не индексация: у строки может быть суррогатная пара —
  // эмодзи в имени, и `[0]` вернул бы половину символа.
  const first = [...(parts[0] ?? '')][0] ?? '?';
  if (parts.length === 1) return first.toUpperCase();

  const last = [...(parts[parts.length - 1] ?? '')][0] ?? '?';
  return (first + last).toUpperCase();
}