/**
 * Код приглашения на клиенте.
 *
 * Проверка формы, а не существования комнаты: существование знает только сервер,
 * и мнимая проверка на клиенте была бы обещанием, которое не сдержится.
 *
 * ─── Почему правила продублированы, а не взяты из `@rd/shared` ───────────────
 *
 * Алфавит и длина живут на сервере (`lib/invite-code.ts`) и на клиенте. Общего
 * пакета для них нет: сервер проверяет код на входе и отвечает 400, а клиент
 * подсказывает ошибку без похода в сеть. Списки совпадают по длине и алфавиту,
 * и это единственное, что от них требуется. Набор проверок разойтись может
 * только если правят одну сторону, и тогда клиент откажет коду, который сервер
 * принял бы, — человек увидит «неверный код» вместо входа.
 *
 * Расхождение ловится тестом: `invite-code.test.ts` сверяет клиентские
 * правила с серверными по всему алфавиту.
 */

/**
 * Ровно тот алфавит, что на сервере: без `0`, `O`, `1`, `I`, `l`.
 *
 * 31 знак: 23 буквы (26 минус три неоднозначные) и 8 цифр. Девяти цифр нет —
 * «0» исключён вместе с «O».
 */
export const INVITE_ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';

/** Восемь знаков: код читают вслух и переписывают на бумаге. */
export const INVITE_LENGTH = 8;

/** Привести к каноническому виду. Регистр не различает сервер. */
export function normalizeInviteCode(raw: string): string {
  return raw.trim().toUpperCase();
}

/**
 * Похоже ли на код приглашения.
 *
 * Проверяет форму: длина и алфавит. Пустая строка — «не код», и на экране это
 * должно читаться как подсказка, а не как ошибка.
 */
export function isValidInviteCode(value: unknown): value is string {
  if (typeof value !== 'string') return false;
  const upper = normalizeInviteCode(value);
  if (upper.length !== INVITE_LENGTH) return false;
  for (const ch of upper) {
    if (!INVITE_ALPHABET.includes(ch)) return false;
  }
  return true;
}

/**
 * Подсказка об алфавите для поля ввода.
 *
 * Показывается всегда, а не по ошибке: человек, который ещё не вводил код,
 * должен знать, какие знаки вообще бывают, иначе он напечатает `0` и получит
 * отказ вместо подсказки.
 */
export function inviteAlphabetHint(): string {
  return `Восемь знаков: латинские буквы и цифры без 0, O, 1, I и l. Допустимы ${INVITE_ALPHABET}`;
}